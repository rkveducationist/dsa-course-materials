public class ArrayTraversalExample {
    public static void main(String[] args) {
        int[] numbers = {5, 10, 15, 20, 25};

        // using for loop
        for (int i = 0; i < numbers.length; i++) {
            System.out.println("Element at Index: " + i + " => " + numbers[i]);
        }
    }
}
